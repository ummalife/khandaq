package com.zoffcc.applications.trifa;

import org.junit.Test;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

/**
 * KHANDAQ (stage 5): the key of a profile without a password comes from SecureRandom, with the alphabet and
 * the length it always had, and no key path draws it from MainActivity.getRandomString (java.util.Random).
 */
public class SecureRandomStringTest
{
    /** The alphabet MainActivity.getRandomString has always used; keys on phones were drawn from it. */
    private static final String ALPHABET =
            "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz!§$%&()=?,.;:-_+";

    @Test
    public void the_alphabet_is_the_one_keys_always_had()
    {
        assertEquals(ALPHABET, SecureRandomString.ALLOWED_CHARACTERS);
        final Set<Character> distinct = new HashSet<>();
        for (final char c : ALPHABET.toCharArray())
        {
            distinct.add(c);
        }
        assertEquals("no character twice, so every one is equally likely", ALPHABET.length(), distinct.size());
    }

    @Test
    public void a_key_has_the_autogen_length_and_only_alphabet_characters()
    {
        for (int i = 0; i < 200; i++)
        {
            final String key = SecureRandomString.next(TRIFAGlobals.LEN_TRIFA_AUTOGEN_PASSWORD);
            assertEquals(32, key.length());
            for (final char c : key.toCharArray())
            {
                assertTrue("not in the alphabet: " + c, ALPHABET.indexOf(c) >= 0);
            }
        }
        assertEquals("", SecureRandomString.next(0));
    }

    @Test
    public void keys_differ_and_reach_the_whole_alphabet()
    {
        final Set<String> keys = new HashSet<>();
        final Set<Character> seen = new HashSet<>();
        for (int i = 0; i < 2000; i++)
        {
            final String key = SecureRandomString.next(TRIFAGlobals.LEN_TRIFA_AUTOGEN_PASSWORD);
            keys.add(key);
            for (final char c : key.toCharArray())
            {
                seen.add(c);
            }
        }
        assertEquals("2000 keys of 32 characters never repeat", 2000, keys.size());
        // 64000 draws over 78 characters: missing one has a chance far below 1e-300.
        assertEquals(ALPHABET.length(), seen.size());
    }

    @Test(expected = IllegalArgumentException.class)
    public void a_negative_length_is_refused()
    {
        SecureRandomString.next(-1);
    }

    @Test
    public void no_key_path_calls_getRandomString() throws IOException
    {
        final List<String> keyFiles = new ArrayList<>();
        final List<String> offenders = new ArrayList<>();
        for (final File file : javaSources())
        {
            final String text = new String(Files.readAllBytes(file.toPath()), StandardCharsets.UTF_8);
            // A key path makes or stores the database key of a profile without a password.
            if (!text.contains("saveAutoGeneratedKey(") && !text.contains("LEN_TRIFA_AUTOGEN_PASSWORD"))
            {
                continue;
            }
            keyFiles.add(file.getName());
            final String[] lines = text.split("\n", -1);
            for (int i = 0; i < lines.length; i++)
            {
                final String line = lines[i];
                final String code = line.trim();
                if (code.startsWith("*") || code.startsWith("/*") || code.startsWith("//"))
                {
                    continue;
                }
                if (line.contains("getRandomString(") && !line.contains("static String getRandomString("))
                {
                    offenders.add(file.getName() + ":" + (i + 1) + ": " + line.trim());
                }
            }
        }
        assertTrue("first launch makes a key: " + keyFiles, keyFiles.contains("AirFirstLaunchActivity.java"));
        assertTrue("the old password screen makes a key: " + keyFiles, keyFiles.contains("SetPasswordActivity.java"));
        assertTrue("getRandomString (java.util.Random) on a key path: " + offenders, offenders.isEmpty());

        final String firstLaunch = source("AirFirstLaunchActivity.java");
        final String setPassword = source("SetPasswordActivity.java");
        assertEquals(2, count(firstLaunch, "getSecureRandomString(LEN_TRIFA_AUTOGEN_PASSWORD)"));
        assertEquals(1, count(setPassword, "getSecureRandomString(LEN_TRIFA_AUTOGEN_PASSWORD)"));
        assertFalse(source("MainActivity.java").contains("ALLOWED_CHARACTERS = \""));
    }

    private static int count(final String text, final String needle)
    {
        int n = 0;
        for (int at = text.indexOf(needle); at >= 0; at = text.indexOf(needle, at + needle.length()))
        {
            n++;
        }
        return n;
    }

    private static String source(final String name) throws IOException
    {
        for (final File file : javaSources())
        {
            if (file.getName().equals(name))
            {
                return new String(Files.readAllBytes(file.toPath()), StandardCharsets.UTF_8);
            }
        }
        throw new AssertionError(name + " not found");
    }

    private static List<File> javaSources()
    {
        // Gradle runs unit tests from the module directory; an IDE may use the project root.
        for (final String root : new String[]{"src/main/java", "app/src/main/java"})
        {
            final File dir = new File(root, "com/zoffcc/applications/trifa");
            final File[] files = dir.listFiles((d, n) -> n.endsWith(".java"));
            if (files != null && files.length > 0)
            {
                final List<File> out = new ArrayList<>();
                for (final File f : files)
                {
                    out.add(f);
                }
                return out;
            }
        }
        throw new AssertionError("src/main/java not found from " + new File("").getAbsolutePath());
    }
}
