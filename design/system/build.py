# ---- DESIGN.md -------------------------------------------------------------------------------------

def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + " --- |" * len(header)]
    out += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return out


def design_tables(tokens, faces):
    """The token part of DESIGN.md, so the document can never disagree with tokens.json."""
    colors = tokens["color"]
    lowest = {}
    for rule in tokens["contrast"]:
        for scheme in SCHEMES:
            for ground in rule["on"]:
                ratio = worst_contrast(colors[rule["fg"]][scheme], colors[ground][scheme])
                key = (rule["fg"], scheme)
                if key not in lowest or ratio < lowest[key][0]:
                    lowest[key] = (ratio, ground)
    grounds = {ground for rule in tokens["contrast"] for ground in rule["on"]}

    def contrast_note(name):
        if (name, "light") in lowest:
            (light, light_on), (dark, dark_on) = lowest[(name, "light")], lowest[(name, "dark")]
            return f"{light:.2f}:1 on `{light_on}` / {dark:.2f}:1 on `{dark_on}`"
        return "ground for text" if name in grounds else "not used for text"

    out = [GENERATED_START, "", "### Palette", "",
           "Lowest contrast is the worst pair from the contrast rules in each theme; `build.py` fails below the threshold.", ""]
    out += table(["Token", "Light", "Dark", "Use", "Lowest contrast as text (light / dark)"],
                 [(f"`{name}`", f"`{spec['light']}`", f"`{spec['dark']}`", spec.get("use", ""), contrast_note(name)) for name, spec in colors.items()])
    out += ["", "### Type roles", ""]
    out += table(["Role", "Family", "Weight", "Desktop px", "Phone px", "iOS style", "Use"],
                 [(f"`{role}`", spec["family"], spec["weight"], "/".join(number(v) for v in spec["desk"]),
                   "/".join(number(v) for v in spec["phone"]), spec["ios-style"], spec["use"]) for role, spec in tokens["font"]["role"].items()])
    out += ["", "### Font files", "",
            "Each client bundles these files from `design/system/fonts` (SIL Open Font License) and loads a face by its PostScript name, read from the file.", ""]
    out += table(["File", "PostScript name", "Family", "Weight"],
                 [(f"`{path.name}`", f"`{postscript}`", family, weight) for (family, weight), (postscript, path) in sorted(faces.items())])
    out += ["", "### Spacing, radius, stroke", "",
            "Spacing scale, px (`--kq-space-N`, `KQSpace.xN`): " + ", ".join(str(v) for v in tokens["space"]) + ".", ""]
    out += table(["Radius", "px"], [(f"`{name}`", value) for name, value in tokens["radius"].items()])
    out += [""]
    out += table(["Stroke", "px"], [(f"`{name}`", number(value)) for name, value in tokens["stroke"].items()])
    out += ["", "### Elevation", "", "Overlays only, drawn in `shadow`; resting elements have no shadow.", ""]
    out += table(["Elevation", "x, y, blur (px)"], [(f"`{name}`", ", ".join(number(v) for v in value)) for name, value in tokens["elevation"].items()])
    out += ["", "### Sizes and breakpoints", ""]
    out += table(["Size", "px"], [(f"`{name}`", value) for name, value in tokens["size"].items()])
    out += [""]
    out += table(["Breakpoint", "max-width px"], [(f"`{name}`", value) for name, value in tokens["breakpoint"].items()])
    motion = tokens["motion"]
    out += ["", "### Motion", ""]
    out += table(["Duration", "ms"], [(f"`{name}`", value) for name, value in motion["duration"].items()])
    out += [""]
    out += table(["Easing", "cubic-bezier"], [(f"`{name}`", ", ".join(number(v) for v in points)) for name, points in motion["easing"].items()])
    out += ["", f"With reduced motion every duration is capped at {motion['reduced']['max-duration']} ms and the stagger is 0.", "", GENERATED_END]
    return "\n".join(out)


def design_md(tokens, faces):
    try:
        current = DESIGN_MD.read_text(encoding="utf-8")
    except OSError as exc:
        raise TokenError(f"cannot read {DESIGN_MD.relative_to(ROOT)}: {exc}") from exc
    if current.count(GENERATED_START) != 1 or current.count(GENERATED_END) != 1:
        raise TokenError(f"{DESIGN_MD.relative_to(ROOT)} must hold the generated-table markers exactly once")
    head, rest = current.split(GENERATED_START, 1)
    _, tail = rest.split(GENERATED_END, 1)
    return head + design_tables(tokens, faces) + tail


# ---- Android ----------------------------------------------------------------------------------------

ANDROID_RES = ROOT / "khandaq-android-trifa" / "android-refimpl-app" / "app" / "src" / "main" / "res"
ANDROID_WEIGHTS = {400: "regular", 500: "medium", 600: "semibold", 700: "bold"}
ANDROID_FAMILY_STEMS = {"text": "ibm_plex_sans", "arabic": "ibm_plex_sans_arabic", "mono": "ibm_plex_mono"}


def android_name(*parts):
    """kq_<parts> in lower case with underscores, the only shape Android resource names accept."""
    return "_".join(("kq",) + tuple(str(part) for part in parts)).replace("-", "_").replace(".", "_").lower()


def android_hex(value):
    """#rrggbb stays as it is; #rrggbbaa becomes Android's #aarrggbb."""
    digits = value[1:].upper()
    return "#" + (digits[6:] + digits[:6] if len(digits) == 8 else digits)


def android_dp(value):
    return f"{number(value)}dp"


def android_font_stem(family, weight):
    return f"{ANDROID_FAMILY_STEMS[family]}_{ANDROID_WEIGHTS[weight]}"


def android_resources(lines):
    return "\n".join(['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {NOTICE} -->", "<resources>", *lines, "</resources>", ""])


def android_colors(tokens, scheme):
    return android_resources([f'    <color name="{android_name(name)}">{android_hex(spec[scheme])}</color>'
                              for name, spec in tokens["color"].items()])


def android_dimens(tokens):
    lines = [f'    <dimen name="{android_name("space", value)}">{android_dp(value)}</dimen>' for value in tokens["space"]]
    for group in ("radius", "stroke", "size"):
        lines += [f'    <dimen name="{android_name(group, name)}">{android_dp(value)}</dimen>'
                  for name, value in tokens[group].items()]
    for role, spec in tokens["font"]["role"].items():
        size, line = spec["phone"]
        lines.append(f'    <dimen name="{android_name("text", role)}">{number(size)}sp</dimen>')
        lines.append(f'    <dimen name="{android_name("line", role)}">{number(line)}sp</dimen>')
    lines += [f'    <integer name="{android_name("dur", name)}">{value}</integer>'
              for name, value in tokens["motion"]["duration"].items()]
    lines.append(f'    <integer name="kq_dur_reduced_max">{tokens["motion"]["reduced"]["max-duration"]}</integer>')
    return android_resources(lines)


def android_type(tokens, script):
    """TextAppearance.KQ.<Role> on the phone scale. The Arabic set swaps the text family for Plex Sans
    Arabic, which carries Latin letters as well, so mixed lines keep one face."""
    lines = []
    for role, spec in tokens["font"]["role"].items():
        family = "arabic" if script == "arabic" and spec["family"] == "text" else spec["family"]
        font = f"@font/{android_font_stem(family, spec['weight'])}"
        style = camel(role)[:1].upper() + camel(role)[1:]
        lines += [
            f'    <style name="TextAppearance.KQ.{style}" parent="">',
            f'        <item name="android:textSize">@dimen/{android_name("text", role)}</item>',
            f'        <item name="android:fontFamily">{font}</item>',
            f'        <item name="fontFamily">{font}</item>',
            f'        <item name="lineHeight">@dimen/{android_name("line", role)}</item>',
            "    </style>",
        ]
    return android_resources(lines)


def android_interpolator(points):
    x1, y1, x2, y2 = (number(value) for value in points)
    return "\n".join([
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {NOTICE} -->",
        '<pathInterpolator xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:controlX1="{x1}"',
        f'    android:controlY1="{y1}"',
        f'    android:controlX2="{x2}"',
        f'    android:controlY2="{y2}" />',
        "",
    ])


ANDROID_ICON_PREFIX = "kq_ic_"
ICON_ELEMENT = re.compile(r"<(path|circle|rect)\s+([^>]*?)\s*/>")
ICON_ATTRIBUTE = re.compile(r'([a-z-]+)="([^"]*)"')


def icon_path_data(inner):
    """One VectorDrawable path for a sprite symbol. VectorDrawable draws only paths, so circles and
    rounded rectangles become arcs; any other element is an error rather than a silently missing line."""
    leftover = ICON_ELEMENT.sub("", inner).strip()
    if leftover:
        raise TokenError(f"icon has an element Android cannot draw: {leftover[:60]}")
    parts = []
    for tag, attributes in ICON_ELEMENT.findall(inner):
        values = dict(ICON_ATTRIBUTE.findall(attributes))
        if tag == "path":
            parts.append(values["d"])
        elif tag == "circle":
            cx, cy, r = (float(values[key]) for key in ("cx", "cy", "r"))
            parts.append(f"M{number(cx - r)},{number(cy)}a{number(r)},{number(r)} 0 1,0 {number(2 * r)},0"
                         f"a{number(r)},{number(r)} 0 1,0 {number(-2 * r)},0z")
        else:
            x, y, w, h = (float(values[key]) for key in ("x", "y", "width", "height"))
            rx = min(float(values.get("rx", "0")), w / 2, h / 2)
            if rx <= 0:
                parts.append(f"M{number(x)},{number(y)}h{number(w)}v{number(h)}h{number(-w)}z")
                continue
            arc = f"a{number(rx)},{number(rx)} 0 0,1"
            parts.append(
                f"M{number(x + rx)},{number(y)}h{number(w - 2 * rx)}{arc} {number(rx)},{number(rx)}"
                f"v{number(h - 2 * rx)}{arc} {number(-rx)},{number(rx)}h{number(-(w - 2 * rx))}"
                f"{arc} {number(-rx)},{number(-rx)}v{number(-(h - 2 * rx))}{arc} {number(rx)},{number(-rx)}z")
    return "".join(parts)


def android_icon_files(tokens):
    """kq_ic_<name>: the sprite as vector drawables, stroked in black and tinted where they are used."""
    width = number(tokens["stroke"]["icon"])
    files = {}
    for name, inner in sorted(icon_symbols().items()):
        files[ANDROID_RES / "drawable" / f"{ANDROID_ICON_PREFIX}{name.replace('-', '_')}.xml"] = "\n".join([
            '<?xml version="1.0" encoding="utf-8"?>',
            f"<!-- {NOTICE} -->",
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
            '    android:width="24dp"',
            '    android:height="24dp"',
            '    android:viewportWidth="24"',
            '    android:viewportHeight="24">',
            "    <path",
            f'        android:pathData="{icon_path_data(inner)}"',
            '        android:fillColor="#00000000"',
            '        android:strokeColor="#FF000000"',
            f'        android:strokeWidth="{width}"',
            '        android:strokeLineCap="round"',
            '        android:strokeLineJoin="round" />',
            "</vector>",
            "",
        ])
    return files


def stray_android_icons(files):
    """Drawables left behind by an icon that no longer exists on the page."""
    folder = ANDROID_RES / "drawable"
    if not folder.exists():
        return []
    return sorted(path for path in folder.glob(f"{ANDROID_ICON_PREFIX}*.xml") if path not in files)


def android_files(tokens, faces):
    files = {
        ANDROID_RES / "values" / "kq_colors.xml": android_colors(tokens, "light"),
        ANDROID_RES / "values-night" / "kq_colors.xml": android_colors(tokens, "dark"),
        ANDROID_RES / "values" / "kq_dimens.xml": android_dimens(tokens),
        ANDROID_RES / "values" / "kq_type.xml": android_type(tokens, "latin"),
        ANDROID_RES / "values-ar" / "kq_type.xml": android_type(tokens, "arabic"),
    }
    for name, points in tokens["motion"]["easing"].items():
        files[ANDROID_RES / "interpolator" / f"{android_name('ease', name)}.xml"] = android_interpolator(points)
    for (family, weight), (_, source) in faces.items():
        files[ANDROID_RES / "font" / f"{android_font_stem(family, weight)}.ttf"] = source.read_bytes()
    files.update(android_icon_files(tokens))
    return files


def artifact_page():
    """The design system page without its document skeleton, for a host that adds its own."""
    lines = PAGE.read_text(encoding="utf-8").split("\n")
    for tag in SKELETON_LINES:
        if sum(1 for line in lines if line.strip() == tag) != 1:
            raise TokenError(f"{PAGE.name} must keep {tag} on its own line, exactly once")
    return "\n".join(line for line in lines if line.strip() not in SKELETON_LINES)


