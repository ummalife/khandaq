def icon_symbols():
    """{name: inner SVG} for every 24x24 symbol in the design system page's sprite."""
    symbols = dict(SYMBOL.findall(PAGE.read_text(encoding="utf-8")))
    if not symbols:
        raise TokenError(f"{PAGE.name} has no icon symbols")
    return symbols


def ios_icon_files(tokens):
    """Template image sets for the asset catalog: a stroked SVG each, the line from the stroke token."""
    width = number(tokens["stroke"]["icon"])
    info = {"info": {"author": "xcode", "version": 1}}
    files = {IOS_ICONS_DIR / "Contents.json": json.dumps(info, indent=2) + "\n"}
    for name, inner in sorted(icon_symbols().items()):
        asset = f"kq-{name}"
        folder = IOS_ICONS_DIR / f"{asset}.imageset"
        files[folder / f"{asset}.svg"] = (
            '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
            f'stroke="#000000" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round">{inner}</svg>\n'
        )
        manifest = {
            "images": [{"filename": f"{asset}.svg", "idiom": "universal"}],
            **info,
            "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"},
        }
        files[folder / "Contents.json"] = json.dumps(manifest, indent=2) + "\n"
    return files


def stray_ios_icons(files):
    """Image sets left in the Air folder by an icon that no longer exists on the page."""
    if not IOS_ICONS_DIR.exists():
        return []
    expected = {path.parent.name for path in files if path.parent.parent == IOS_ICONS_DIR}
    return sorted(path for path in IOS_ICONS_DIR.glob("*.imageset") if path.name not in expected)


