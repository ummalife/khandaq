class TokenError(Exception):
    pass


def load(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise TokenError(f"{path.relative_to(ROOT)}: {exc}") from exc


def rgba(value):
    if not HEX.match(value):
        raise TokenError(f"not a #rrggbb or #rrggbbaa colour: {value}")
    digits = value[1:]
    alpha = int(digits[6:8], 16) if len(digits) == 8 else 255
    return int(digits[0:2], 16), int(digits[2:4], 16), int(digits[4:6], 16), alpha


def luminance(value):
    def channel(c):
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b, _ = rgba(value)
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast(fg, bg):
    a, b = luminance(fg), luminance(bg)
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


def composite(top, bottom):
    """Lays a colour that may be translucent over an opaque one, the way the screen blends them."""
    r1, g1, b1, a1 = rgba(top)
    r2, g2, b2, _ = rgba(bottom)
    alpha = a1 / 255
    mixed = (round(c1 * alpha + c2 * (1 - alpha)) for c1, c2 in ((r1, r2), (g1, g2), (b1, b2)))
    return "#" + "".join(f"{c:02x}" for c in mixed)


def worst_contrast(fg, bg):
    """Contrast of a pair in which either colour may be translucent.

    A translucent ground is tried over black and over white, the two extremes of whatever lies under
    it; a translucent foreground is laid over the ground. The lower ratio counts.
    """
    grounds = [bg] if rgba(bg)[3] == 255 else [composite(bg, "#000000"), composite(bg, "#ffffff")]
    return min(contrast(fg if rgba(fg)[3] == 255 else composite(fg, ground), ground) for ground in grounds)


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def number(value):
    return f"{value:g}"


