def outputs(tokens):
    """Every generated file: text as str, font copies as bytes."""
    roles = ios_roles(tokens)
    faces = font_faces(tokens)
    check_ios_font_registration(faces)
    files = {
        HERE / "dist" / "tokens.css": css(tokens),
        # The site serves its own copy; generating it here is what keeps the two from drifting apart.
        SITE_TOKENS: css(tokens),
        HERE / "dist" / "tokens.js": js(tokens),
        ARTIFACT_PAGE: artifact_page(),
        IOS_DIR / "default-theme.yaml": ios_yaml(tokens, roles, "light"),
        IOS_DIR / "dark-theme.yaml": ios_yaml(tokens, roles, "dark"),
        IOS_DIR / "DesignTokens.swift": ios_swift(tokens, faces),
        DESIGN_MD: design_md(tokens, faces),
    }
    for _, source in faces.values():
        files[IOS_FONTS_DIR / source.name] = source.read_bytes()
    files.update(ios_icon_files(tokens))
    files.update(android_files(tokens, faces))
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify the generated files instead of writing them")
    args = parser.parse_args()

    try:
        tokens = load(TOKENS)
        validate(tokens)
        failures = contrast_failures(tokens)
        if failures:
            print("contrast: " + str(len(failures)) + " failing pair(s)", file=sys.stderr)
            for line in failures:
                print("  " + line, file=sys.stderr)
            return 1
        files = outputs(tokens)
    except TokenError as exc:
        print(f"tokens: {exc}", file=sys.stderr)
        return 1

    stale = []
    for path, content in files.items():
        binary = isinstance(content, bytes)
        current = (path.read_bytes() if binary else path.read_text(encoding="utf-8")) if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if binary:
            path.write_bytes(content)
        else:
            path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}", flush=True)
        if path == SITE_TOKENS:
            # A new tokens.css needs a new ?v= stamp in every page that links it, or CI and
            # deploy-site.sh refuse the site. Restamp here so a token change is one command.
            subprocess.run([sys.executable, str(SITE_STAMPER)], check=True)

    for folder in stray_ios_icons(files):
        if args.check:
            stale.append(folder)
            continue
        for item in folder.iterdir():
            item.unlink()
        folder.rmdir()
        print(f"removed {folder.relative_to(ROOT)}")

    for drawable in stray_android_icons(files):
        if args.check:
            stale.append(drawable)
            continue
        drawable.unlink()
        print(f"removed {drawable.relative_to(ROOT)}")

    if stale:
        print("tokens: out of date, run design/system/build.py:", file=sys.stderr)
        for path in stale:
            print(f"  {path.relative_to(ROOT)}", file=sys.stderr)
        return 1
    print(f"tokens: {len(tokens['color'])} colours, {len(tokens['contrast'])} contrast rules, {len(files)} files up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
