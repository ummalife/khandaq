def ios_role_names():
    try:
        source = THEME_SWIFT.read_text(encoding="utf-8")
    except OSError as exc:
        raise TokenError(f"cannot read {THEME_SWIFT.relative_to(ROOT)}: {exc}") from exc
    block = source.split("enum ColorType", 1)[1].split("static let allValues", 1)[0]
    return re.findall(r'case \w+ = "([a-z0-9-]+)"', block)


def ios_roles(tokens):
    roles = {k: v for k, v in load(IOS_ROLES).items() if not k.startswith("$")}
    expected = ios_role_names()
    missing = [r for r in expected if r not in roles]
    unknown = [r for r in roles if r not in expected]
    bad = [f"{r} -> {t}" for r, t in roles.items() if t not in tokens["color"]]
    if missing or unknown or bad:
        parts = []
        if missing:
            parts.append("missing roles: " + ", ".join(missing))
        if unknown:
            parts.append("roles Theme.swift does not know: " + ", ".join(unknown))
        if bad:
            parts.append("unknown tokens: " + ", ".join(bad))
        raise TokenError("ios-theme-roles.json: " + "; ".join(parts))
    return [(role, roles[role]) for role in expected]


def ios_yaml(tokens, roles, scheme):
    used = sorted({token for _, token in roles})
    out = ["version: 1", "", f"# {NOTICE}", f"# Direction B (Air), {scheme} theme.", "", "colors:"]
    for name in used:
        out.append(f'  {name}: "{tokens["color"][name][scheme][1:].upper()}"')
    out += ["", "values:"]
    out += [f'  {role}: "{token}"' for role, token in roles]
    out.append("")
    return "\n".join(out)


def ios_hex(value):
    r, g, b, a = rgba(value)
    return f"0x{r:02X}{g:02X}{b:02X}{a:02X}"


