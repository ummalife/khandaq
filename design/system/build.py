def font_face(path):
    """The PostScript name and weight class of a TrueType font, read from its name and OS/2 tables.

    Clients load a face by its PostScript name, and IBM Plex abbreviates it (IBMPlexSans-Medm,
    IBMPlexSans-SmBld), so the name is taken from the file rather than guessed from the weight.
    """
    data = path.read_bytes()
    where = path.relative_to(ROOT)
    try:
        tables = {}
        for index in range(struct.unpack(">H", data[4:6])[0]):
            tag, _, offset, length = struct.unpack(">4sIII", data[12 + 16 * index: 28 + 16 * index])
            tables[tag] = (offset, length)
        if b"name" not in tables or b"OS/2" not in tables:
            raise TokenError(f"{where}: no name or OS/2 table, not a usable font")
        weight = struct.unpack(">H", data[tables[b"OS/2"][0] + 4: tables[b"OS/2"][0] + 6])[0]
        base = tables[b"name"][0]
        _, count, strings = struct.unpack(">HHH", data[base: base + 6])
        for index in range(count):
            platform, _, _, name_id, length, offset = struct.unpack(">HHHHHH", data[base + 6 + 12 * index: base + 18 + 12 * index])
            if name_id != 6:
                continue
            raw = data[base + strings + offset: base + strings + offset + length]
            return (raw.decode("utf-16-be") if platform in (0, 3) else raw.decode("latin-1")), weight
    except (struct.error, UnicodeDecodeError) as exc:
        raise TokenError(f"{where}: unreadable font ({exc})") from exc
    raise TokenError(f"{where}: the name table has no PostScript name")


def font_faces(tokens):
    """{(family, weight): (PostScript name, path)} for every file in design/system/fonts.

    A file belongs to the family whose iOS name is its PostScript name or the stem before a hyphen, so
    IBMPlexSans-Medm is text and IBMPlexSansArabic-Medm is arabic. Every weight a role asks for must
    have a file, for Arabic as well as Latin text.
    """
    families = tokens["font"]["family"]
    faces = {}
    for path in sorted(FONTS_DIR.glob("*.ttf")):
        postscript, weight = font_face(path)
        owners = [name for name, spec in families.items() if postscript == spec["ios"] or postscript.startswith(spec["ios"] + "-")]
        if len(owners) != 1:
            raise TokenError(f"{path.relative_to(ROOT)} ({postscript}) matches {len(owners)} font families, needs exactly one")
        key = (owners[0], weight)
        if key in faces:
            raise TokenError(f"{path.name} and {faces[key][1].name} are both {owners[0]} at weight {weight}")
        faces[key] = (postscript, path)
    for role, spec in tokens["font"]["role"].items():
        for family in (("text", "arabic") if spec["family"] == "text" else (spec["family"],)):
            if (family, spec["weight"]) not in faces:
                raise TokenError(f"font role {role} needs {family} at weight {spec['weight']}, and design/system/fonts has no such file")
    return faces


def check_ios_font_registration(faces):
    """The copied fonts are useless unless Info.plist lists them and the app target copies them."""
    names = sorted(path.name for _, path in faces.values())
    try:
        with IOS_INFO_PLIST.open("rb") as handle:
            listed = sorted(plistlib.load(handle).get("UIAppFonts", []))
        project = IOS_PROJECT.read_text(encoding="utf-8")
    except (OSError, plistlib.InvalidFileException) as exc:
        raise TokenError(f"cannot read the iOS project: {exc}") from exc
    if listed != names:
        raise TokenError(f"{IOS_INFO_PLIST.relative_to(ROOT)} UIAppFonts must list exactly {', '.join(names)}; it lists {', '.join(listed) or 'nothing'}")
    missing = [name for name in names if f"/* {name} in Resources */" not in project]
    if missing:
        raise TokenError(f"{IOS_PROJECT.relative_to(ROOT)} does not copy {', '.join(missing)} into the app")
    strays = sorted(path.name for path in IOS_FONTS_DIR.glob("*") if path.name not in names) if IOS_FONTS_DIR.exists() else []
    if strays:
        raise TokenError(f"{IOS_FONTS_DIR.relative_to(ROOT)} holds files that are not in design/system/fonts: {', '.join(strays)}")


def validate(tokens):
    colors = tokens["color"]
    for name, spec in colors.items():
        for scheme in SCHEMES:
            if scheme not in spec:
                raise TokenError(f"colour {name} has no {scheme} value")
            rgba(spec[scheme])
    for rule in tokens["contrast"]:
        for name in [rule["fg"], *rule["on"]]:
            if name not in colors:
                raise TokenError(f"contrast rule names an unknown colour: {name}")
    if "shadow" not in colors:
        raise TokenError("elevation needs a shadow colour")
    for name, value in tokens["elevation"].items():
        if not (isinstance(value, list) and len(value) == 3 and all(isinstance(v, (int, float)) for v in value)):
            raise TokenError(f"elevation {name} must be [x, y, blur]")
    widths = set(tokens["breakpoint"].values())
    for found in re.findall(r"@media[^{]*?\(max-width:\s*(\d+)px\)", PAGE_CSS.read_text(encoding="utf-8")):
        if int(found) not in widths:
            raise TokenError(f"{PAGE_CSS.relative_to(ROOT)} breaks at {found}px, which is not a breakpoint token")
    for role in tokens["font"]["role"]:
        if not re.fullmatch(r"[a-z]+(?:-[a-z]+)*", role):
            raise TokenError(f"font role name must be lowercase words joined by hyphens: {role}")


def contrast_failures(tokens):
    colors = tokens["color"]
    failures = []
    for rule in tokens["contrast"]:
        for scheme in SCHEMES:
            fg = colors[rule["fg"]][scheme]
            for ground in rule["on"]:
                bg = colors[ground][scheme]
                ratio = worst_contrast(fg, bg)
                if ratio < rule["min"]:
                    failures.append(f"{scheme}: {rule['fg']} {fg} on {ground} {bg} is {ratio:.2f}:1, needs {rule['min']}:1")
    return failures


