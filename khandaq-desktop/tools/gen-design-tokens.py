"""Writes the desktop client's share of the design system.

Everything the desktop draws with comes from design/system: colours, sizes, the type scale and motion
from tokens.json, the icons from the sprite on the design system page (index.html), the IBM Plex faces
from design/system/fonts. Nothing of it is copied by hand. This script writes:

  src/widget/air/airtokens.h      every token as a C++ constant
  img/air/*.svg                   one stroked SVG per icon, coloured at run time
  res/font/plex/*                 the Plex faces and their OFL licence
  res/air.qrc                     the resource file for the icons and faces
  themes/default/palette.ini      the legacy palette of the light theme, from the light tokens
  themes/dark/palette.ini         the same for the dark theme

Usage: gen-design-tokens.py [--check]
With --check nothing is written: the script fails if any of these files is stale or missing, or if a
file in img/air or res/font/plex is no longer produced.
"""

import argparse
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
DESKTOP = HERE.parent
DESIGN = DESKTOP.parent / "design" / "system"
TOKENS = DESIGN / "tokens.json"
PAGE = DESIGN / "index.html"
FONTS = DESIGN / "fonts"

HEADER = DESKTOP / "src" / "widget" / "air" / "airtokens.h"
ICONS_DIR = DESKTOP / "img" / "air"
FONT_DIR = DESKTOP / "res" / "font" / "plex"
QRC = DESKTOP / "res" / "air.qrc"
PALETTES = {
    "light": DESKTOP / "themes" / "default" / "palette.ini",
    "dark": DESKTOP / "themes" / "dark" / "palette.ini",
}

SYMBOL = re.compile(r'<symbol id="i-([a-z0-9-]+)" viewBox="0 0 24 24">(.*?)</symbol>')
HEX = re.compile(r"^#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?$")
FIRST_FAMILY = re.compile(r'^"([^"]+)"')

# The legacy widgets read these names from palette.ini (Style::ColorPalette). Each one takes the token
# that does the same job, so the old forms follow the new colours in both themes: buttons are ink,
# green means reachable, amber on its way, red broken.
LEGACY_PALETTE = [
    ("transferGood", "live"),
    ("transferWait", "transit"),
    ("transferBad", "danger"),
    ("transferMiddle", "line-strong"),
    ("mainText", "ink"),
    ("nameActive", "ink"),
    ("statusActive", "live"),
    ("groundExtra", "ink-3"),
    ("groundBase", "surface"),
    ("orange", "transit"),
    ("yellow", "transit-soft"),
    ("themeDark", "raised"),
    ("themeMediumDark", "sunken"),
    ("themeMedium", "sunken"),
    ("themeLight", "selected"),
    ("action", "ink"),
    ("link", "ink"),
    ("searchHighlighted", "transit"),
    ("selectText", "selected"),
]

# CSS weights to Qt 5 QFont::Weight.
QT_WEIGHTS = {400: "QFont::Normal", 500: "QFont::Medium", 600: "QFont::DemiBold"}

GENERATED_NOTE = (
    "Generated by tools/gen-design-tokens.py from design/system. Do not edit by hand: change the\n"
    "tokens and run the script again."
)


class TokenError(Exception):
    pass


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def pascal(name):
    return "".join(part[:1].upper() + part[1:] for part in name.split("-"))


def number(value):
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise TokenError(f"{value!r} is not a number")
    if float(value).is_integer():
        return str(int(value))
    return repr(float(value))


def argb(value):
    match = HEX.match(value)
    if not match:
        raise TokenError(f"{value!r} is not a #rrggbb or #rrggbbaa colour")
    rgb, alpha = match.group(1), match.group(2) or "ff"
    return f"0x{alpha.lower()}{rgb.lower()}"


def css_rgb(value):
    """palette.ini goes through QColor, which reads #aarrggbb: keep the colour opaque there."""
    match = HEX.match(value)
    if not match or match.group(2):
        raise TokenError(f"legacy palette colour {value!r} must be opaque")
    return f"#{match.group(1).lower()}"


def load_tokens():
    try:
        return json.loads(TOKENS.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise TokenError(f"cannot read {TOKENS}: {error}")


def icon_symbols():
    symbols = dict(SYMBOL.findall(PAGE.read_text(encoding="utf-8")))
    if not symbols:
        raise TokenError(f"{PAGE.name} has no icon symbols")
    return dict(sorted(symbols.items()))


def font_files():
    faces = sorted(path for path in FONTS.glob("*.ttf"))
    if not faces:
        raise TokenError(f"no fonts in {FONTS}")
    licence = FONTS / "OFL.txt"
    if not licence.exists():
        raise TokenError(f"{licence} is missing")
    return faces + [licence]


def family_name(tokens, key):
    css = tokens["font"]["family"][key]["css"]
    match = FIRST_FAMILY.match(css)
    if not match:
        raise TokenError(f"font family {key} has no quoted first family: {css!r}")
    return match.group(1)


def header_text(tokens, icons, faces):
    colors = tokens["color"]
    names = sorted(colors)
    lines = [
        "/*",
        "    " + GENERATED_NOTE.replace("\n", "\n    "),
        "*/",
        "",
        "#pragma once",
        "",
        "#include <QFont>",
        "#include <QRgb>",
        "",
        "// Kept as generated: tools/format-code.sh would otherwise repack the tables.",
        "// clang-format off",
        "namespace AirTokens {",
        "",
        "// The palette, one value per theme. Colours are #AARRGGBB.",
        "enum class Color : int",
        "{",
    ]
    lines += [f"    {pascal(name)}," for name in names]
    lines += ["};", "", f"constexpr int colorCount = {len(names)};", ""]
    for theme in ("light", "dark"):
        lines.append(f"constexpr QRgb {theme}Colors[colorCount] = {{")
        for name in names:
            lines.append(f"    {argb(colors[name][theme])}, // {name}")
        lines += ["};", ""]

    tones = sorted(name for name in names if name.startswith("tone-"))
    lines.append("// Identity tones for initials on a tile, in index order.")
    lines.append("constexpr Color tones[] = {")
    lines += [f"    Color::{pascal(name)}," for name in tones]
    lines += ["};", f"constexpr int toneCount = {len(tones)};", ""]

    lines.append("namespace Space {")
    for value in tokens["space"]:
        lines.append(f"constexpr int s{number(value)} = {number(value)};")
    lines += ["} // namespace Space", ""]

    for group, kind in (("radius", "int"), ("size", "int"), ("stroke", "double")):
        lines.append(f"namespace {group.capitalize()} {{")
        for name, value in sorted(tokens[group].items()):
            lines.append(f"constexpr {kind} {camel(name)} = {number(value)};")
        lines += [f"}} // namespace {group.capitalize()}", ""]

    motion = tokens["motion"]
    lines.append("namespace Motion {")
    for name, value in sorted(motion["duration"].items()):
        lines.append(f"constexpr int {camel(name)} = {number(value)};")
    lines.append(f"constexpr int reducedMaxDuration = {number(motion['reduced']['max-duration'])};")
    for name, points in sorted(motion["easing"].items()):
        if len(points) != 4:
            raise TokenError(f"easing {name} needs four control values")
        values = ", ".join(number(point) for point in points)
        lines.append(f"constexpr double ease{pascal(name)}[4] = {{{values}}};")
    lines += ["} // namespace Motion", ""]

    lines += [
        "// Shadows of overlays: offset and blur in the shadow colour.",
        "namespace Elevation {",
        "struct Shadow",
        "{",
        "    int x;",
        "    int y;",
        "    int blur;",
        "};",
    ]
    for name, points in sorted(tokens["elevation"].items()):
        if len(points) != 3:
            raise TokenError(f"elevation {name} needs x, y and blur")
        x, y, blur = (number(point) for point in points)
        lines.append(f"constexpr Shadow {camel(name)} = {{{x}, {y}, {blur}}};")
    lines += ["} // namespace Elevation", ""]

    roles = tokens["font"]["role"]
    lines += [
        "// The desktop type scale: pixel size, line height, weight and family of each text role.",
        "enum class TextRole : int",
        "{",
    ]
    lines += [f"    {pascal(name)}," for name in sorted(roles)]
    lines += ["};", "", "enum class FontFamily : int", "{", "    Text,", "    Mono,", "};", ""]
    lines += [
        "struct TypeStyle",
        "{",
        "    double pixelSize;",
        "    double lineHeight;",
        "    int weight;",
        "    FontFamily family;",
        "};",
        "",
        "constexpr TypeStyle desktopType[] = {",
    ]
    for name in sorted(roles):
        role = roles[name]
        size, height = role["desk"]
        weight = QT_WEIGHTS.get(role["weight"])
        if weight is None:
            raise TokenError(f"type role {name} has an unsupported weight {role['weight']}")
        family = {"text": "Text", "mono": "Mono"}.get(role["family"])
        if family is None:
            raise TokenError(f"type role {name} has an unknown family {role['family']}")
        lines.append(f"    {{{number(size)}, {number(height)}, {weight}, FontFamily::{family}}}, // {name}")
    lines += ["};", ""]

    lines += [
        f'constexpr const char textFamily[] = "{family_name(tokens, "text")}";',
        f'constexpr const char arabicFamily[] = "{family_name(tokens, "arabic")}";',
        f'constexpr const char monoFamily[] = "{family_name(tokens, "mono")}";',
        "",
        "// The bundled faces, as resource paths for QFontDatabase::addApplicationFont().",
        "constexpr const char* fontResources[] = {",
    ]
    lines += [f'    ":/font/plex/{face.name}",' for face in faces if face.suffix == ".ttf"]
    lines += ["};", "", "// Every icon of the sprite by name: the resource is :/img/air/<name>.svg, stroked in black.",
              "constexpr const char* iconNames[] = {"]
    lines += [f'    "{name}",' for name in icons]
    lines += ["};", "", "} // namespace AirTokens", "// clang-format on", ""]
    return "\n".join(lines)


def icon_text(tokens, inner):
    width = number(tokens["stroke"]["icon"])
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
        f'stroke="#000000" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round">{inner}</svg>\n'
    )


def qrc_text(icons, faces):
    lines = ["<!-- " + GENERATED_NOTE.replace("\n", " ") + " -->", "<RCC>", '    <qresource prefix="/img/air">']
    lines += [f'        <file alias="{name}.svg">../img/air/{name}.svg</file>' for name in icons]
    lines += ["    </qresource>", '    <qresource prefix="/font/plex">']
    lines += [f'        <file alias="{face.name}">font/plex/{face.name}</file>' for face in faces]
    lines += ["    </qresource>", "</RCC>", ""]
    return "\n".join(lines)


def palette_text(tokens, theme):
    colors = tokens["color"]
    lines = ["; " + GENERATED_NOTE.replace("\n", "\n; "), "[colors]"]
    for key, token in LEGACY_PALETTE:
        if token not in colors:
            raise TokenError(f"legacy palette key {key} names an unknown token {token}")
        lines.append(f'{key}="{css_rgb(colors[token][theme])}"')
    return "\n".join(lines) + "\n"


def expected_files():
    tokens = load_tokens()
    icons = icon_symbols()
    faces = font_files()
    files = {HEADER: header_text(tokens, icons, faces).encode("utf-8")}
    for name, inner in icons.items():
        files[ICONS_DIR / f"{name}.svg"] = icon_text(tokens, inner).encode("utf-8")
    for face in faces:
        files[FONT_DIR / face.name] = face.read_bytes()
    files[QRC] = qrc_text(icons, faces).encode("utf-8")
    for theme, path in PALETTES.items():
        files[path] = palette_text(tokens, theme).encode("utf-8")
    return files


def strays(files):
    found = []
    for folder in (ICONS_DIR, FONT_DIR):
        if folder.exists():
            found += [path for path in sorted(folder.iterdir()) if path.is_file() and path not in files]
    return found


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail on stale files instead of writing")
    args = parser.parse_args()

    try:
        files = expected_files()
    except TokenError as error:
        print(f"gen-design-tokens: {error}", file=sys.stderr)
        return 2

    if args.check:
        stale = [path for path, data in files.items() if not path.exists() or path.read_bytes() != data]
        extra = strays(files)
        for path in stale:
            print(f"stale or missing: {path.relative_to(DESKTOP)}", file=sys.stderr)
        for path in extra:
            print(f"no longer generated: {path.relative_to(DESKTOP)}", file=sys.stderr)
        if stale or extra:
            print("run khandaq-desktop/tools/gen-design-tokens.py", file=sys.stderr)
            return 1
        print(f"design tokens up to date ({len(files)} files)")
        return 0

    for path in strays(files):
        path.unlink()
    for path, data in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
