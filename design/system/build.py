def css(tokens):
    colors = tokens["color"]
    motion = tokens["motion"]
    reduced = motion["reduced"]["max-duration"]

    def color_lines(scheme, indent):
        return [f"{indent}--kq-{name}: {spec[scheme].lower()};" for name, spec in colors.items()]

    def type_lines(device, indent):
        lines = []
        for role, spec in tokens["font"]["role"].items():
            size, line = spec[device]
            lines.append(f"{indent}--kq-type-{role}: {spec['weight']} {number(size)}px/{number(line)}px var(--kq-font-{spec['family']});")
        return lines

    out = [f"/* {NOTICE} */", "", ":root {", "  color-scheme: light;"]
    out += color_lines("light", "  ")
    out += [f"  --kq-space-{value}: {value}px;" for value in tokens["space"]]
    out += [f"  --kq-radius-{name}: {value}px;" for name, value in tokens["radius"].items()]
    out += [f"  --kq-stroke-{name}: {number(value)}px;" for name, value in tokens["stroke"].items()]
    out += [f"  --kq-size-{name}: {value}px;" for name, value in tokens["size"].items()]
    out += [f"  --kq-elevation-{name}: {' '.join(f'{number(v)}px' for v in value)} var(--kq-shadow);" for name, value in tokens["elevation"].items()]
    out += [f"  --kq-font-{name}: {spec['css']};" for name, spec in tokens["font"]["family"].items()]
    out += type_lines("desk", "  ")
    out += [f"  --kq-dur-{name}: {value}ms;" for name, value in motion["duration"].items()]
    out += [f"  --kq-ease-{name}: cubic-bezier({', '.join(number(v) for v in points)});" for name, points in motion["easing"].items()]
    out += ["}", "", f"@media (max-width: {tokens['breakpoint']['phone']}px) {{", "  :root {"]
    out += type_lines("phone", "    ")
    out += ["  }", "}", "", "@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {', "    color-scheme: dark;"]
    out += color_lines("dark", "    ")
    out += ["  }", "}", "", ':root[data-theme="dark"] {', "  color-scheme: dark;"]
    out += color_lines("dark", "  ")
    out += ["}", "", "@media (prefers-reduced-motion: reduce) {", "  :root {"]
    for name, value in motion["duration"].items():
        capped = 0 if name == "stagger" else min(value, reduced)
        out.append(f"    --kq-dur-{name}: {capped}ms;")
    out += ["  }", "}", ""]
    return "\n".join(out)


