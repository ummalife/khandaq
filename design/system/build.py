    out += [f"    static let {camel(name)}: TimeInterval = {value / 1000:g}" for name, value in motion["duration"].items()]
    for name, (x1, y1, x2, y2) in motion["easing"].items():
        out.append(f"    static let ease{name[:1].upper() + name[1:]} = UICubicTimingParameters(controlPoint1: CGPoint(x: {number(x1)}, y: {number(y1)}), controlPoint2: CGPoint(x: {number(x2)}, y: {number(y2)}))")
    reduced = motion["reduced"]["max-duration"] / 1000
    out += [
        "",
        "    /// The duration to use right now: capped when the person asked the system to reduce motion.",
        "    static func duration(_ value: TimeInterval) -> TimeInterval {",
        f"        return UIAccessibilityIsReduceMotionEnabled() ? min(value, {reduced:g}) : value",
        "    }",
        "}",
        "",
        "enum KQFontRole: CaseIterable {",
    ]
    roles = tokens["font"]["role"]
    out += [f"    case {camel(role)}" for role in roles]
    out += [
        "}",
        "",
        "enum KQFont {",
        "    private struct Spec {",
        "        let family: String",
        "        let weight: Int",
        "        let size: CGFloat",
        "        let lineHeight: CGFloat",
        "        let style: UIFontTextStyle",
        "    }",
        "",
        "    private static func spec(_ role: KQFontRole) -> Spec {",
        "        switch role {",
    ]
    for role, spec in roles.items():
        size, line = spec["phone"]
        out.append(f'            case .{camel(role)}: return Spec(family: "{spec["family"]}", weight: {spec["weight"]}, size: {number(size)}, lineHeight: {number(line)}, style: .{spec["ios-style"]})')
    out += [
        "        }",
        "    }",
        "",
        "    /// The font for a role, scaled with the person's text size: IBM Plex from the app bundle, or the",
        "    /// system face of the same weight if a file is ever missing, so layouts never break.",
        "    static func font(_ role: KQFontRole) -> UIFont {",
        "        let spec = spec(role)",
        "        let base = bundled(spec) ?? system(spec)",
        "        return UIFontMetrics(forTextStyle: spec.style).scaledFont(for: base)",
        "    }",
        "",
        "    /// A role's size, line height and scaling at another weight of its family, as the system page",
        "    /// sets them: a list row's name is the body size at 600, its last message the label size at 400.",
        "    static func font(_ role: KQFontRole, weight: Int) -> UIFont {",
        "        let base = spec(role)",
        "        let variant = Spec(family: base.family, weight: weight, size: base.size, lineHeight: base.lineHeight, style: base.style)",
        "        let font = bundled(variant) ?? system(variant)",
        "        return UIFontMetrics(forTextStyle: variant.style).scaledFont(for: font)",
        "    }",
        "",
        "    /// Line height for a role at the default text size, scaled the same way as the font.",
        "    static func lineHeight(_ role: KQFontRole) -> CGFloat {",
        "        let spec = spec(role)",
        "        return UIFontMetrics(forTextStyle: spec.style).scaledValue(for: spec.lineHeight)",
        "    }",
        "",
        "    /// The same font with tabular figures, for times, counters and sizes that must not jump.",
        "    static func tabular(_ font: UIFont) -> UIFont {",
        "        let settings: [[UIFontDescriptor.FeatureKey: Int]] = [[",
        "            .featureIdentifier: kNumberSpacingType,",
        "            .typeIdentifier: kMonospacedNumbersSelector,",
        "        ]]",
        "        let descriptor = font.fontDescriptor.addingAttributes([.featureSettings: settings])",
        "        return UIFont(descriptor: descriptor, size: 0)",
        "    }",
        "",
        "    private static func bundled(_ spec: Spec) -> UIFont? {",
        "        let family = spec.family == \"text\" && AppLanguage.current == \"ar\" ? \"arabic\" : spec.family",
        "        guard let name = postScriptName(family: family, weight: spec.weight) else {",
        "            return nil",
        "        }",
        "        return UIFont(name: name, size: spec.size)",
        "    }",
        "",
        "    /// PostScript names read from the font files by build.py: Plex abbreviates its weights (Medm, SmBld).",
        "    static func postScriptName(family: String, weight: Int) -> String? {",
        "        switch (family, weight) {",
    ]
    for (family, weight), (postscript, _) in sorted(faces.items()):
        out.append(f'            case ("{family}", {weight}): return "{postscript}"')
    out += [
        "            default: return nil",
        "        }",
        "    }",
        "",
        "    /// The font files Info.plist registers, copied from design/system/fonts by build.py.",
        "    static let bundledFiles = [",
    ]
    out += [f'        "{path.name}",' for _, path in sorted(faces.values(), key=lambda face: face[1].name)]
    out += [
        "    ]",
        "",
        "    private static func system(_ spec: Spec) -> UIFont {",
        "        let weight = systemWeight(spec.weight)",
        "        if spec.family == \"mono\" {",
        "            return UIFont.monospacedSystemFont(ofSize: spec.size, weight: weight)",
        "        }",
        "        return UIFont.systemFont(ofSize: spec.size, weight: weight)",
        "    }",
        "",
        "    private static func systemWeight(_ weight: Int) -> UIFont.Weight {",
        "        switch weight {",
    ]
    for weight, system in IOS_WEIGHTS.items():
        out.append(f"            case {weight}: return {system}")
    out += ["            default: return .regular", "        }", "    }", "}", ""]
    return "\n".join(out)


